#!/usr/bin/env python3
"""Interactive annotation CLI for TREC-style relevance pool.

Reads a pool markdown file generated by `eval_prefetch_quality.py generate-pool`,
shows each paper one at a time, accepts keyboard input, and writes labels back
to the same file.

Usage:
  bash bin/run_py.sh scripts/annotate_pool.py \\
    data/eval_archive/week-2026-W22-pool-102316879.md
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def _extract_papers(text: str) -> list[dict]:
    """Parse pool markdown into paper records."""
    papers = []
    block_re = re.compile(
        r"### (P\d+)\s+<!--\s*(\S+)\s*-->(.*?)(?=\n### |\Z)",
        re.DOTALL,
    )
    for m in block_re.finditer(text):
        p_id = m.group(1)
        axid = m.group(2)
        body = m.group(3)

        title_m = re.search(r"\*\*Title:\*\*\s*(.+)", body)
        cats_m = re.search(r"\*\*Categories:\*\*\s*(.+)", body)
        abstract_m = re.search(r"\*\*Abstract:\*\*\s*(.+)", body)
        rel_m = re.search(r"\*\*Relevance \(0-3\):\*\*\s*(\S+)", body)
        thread_m = re.search(r"\*\*Thread \(if ≥1\):\*\*\s*(\S+)", body)

        papers.append({
            "p_id": p_id,
            "arxiv_id": axid,
            "title": (title_m.group(1) if title_m else "").strip(),
            "categories": (cats_m.group(1) if cats_m else "").strip(),
            "abstract": (abstract_m.group(1) if abstract_m else "").strip(),
            "current_relevance": (rel_m.group(1) if rel_m else "___"),
            "current_thread": (thread_m.group(1) if thread_m else "___"),
        })
    return papers


def _write_label(text: str, axid: str, relevance: int, thread: str) -> str:
    """Replace the Relevance and Thread lines for a given arxiv_id."""
    def replace_rel(m: re.Match) -> str:
        return m.group(0).replace(m.group(1), str(relevance))

    # Find the paper block for this axid
    block_start = text.find(f"<!-- {axid} -->")
    if block_start == -1:
        return text

    # Replace Relevance line within block
    block_end = text.find("\n### ", block_start + 1)
    block = text[block_start:block_end] if block_end != -1 else text[block_start:]

    block = re.sub(
        r"(\*\*Relevance \(0-3\):\*\*\s*)(\S+)",
        lambda m: m.group(1) + str(relevance),
        block,
    )
    block = re.sub(
        r"(\*\*Thread \(if ≥1\):\*\*\s*)(\S+)",
        lambda m: m.group(1) + (thread if thread else "___"),
        block,
    )

    if block_end != -1:
        return text[:block_start] + block + text[block_end:]
    return text[:block_start] + block


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: annotate_pool.py <pool.md>")
        return 1

    pool_path = Path(sys.argv[1])
    if not pool_path.exists():
        print(f"File not found: {pool_path}"); return 1

    text = pool_path.read_text()
    papers = _extract_papers(text)

    # Count already labeled
    labeled = [p for p in papers if p["current_relevance"] not in ("___", "")]
    todo = [p for p in papers if p["current_relevance"] in ("___", "")]

    print(f"\n{'='*60}")
    print(f"Pool: {pool_path.name}")
    print(f"Total: {len(papers)} papers | Already labeled: {len(labeled)} | Remaining: {len(todo)}")
    print(f"{'='*60}")
    print("Enter relevance 0-3, then thread name (or press Enter to skip thread).")
    print("Press Ctrl+C or type 'q' to quit and save.\n")

    for i, p in enumerate(todo, 1):
        print(f"\n[{i}/{len(todo)}] {p['p_id']} | {p['arxiv_id']}")
        print(f"  Categories: {p['categories']}")
        print(f"  Title: {p['title'][:90]}")
        print(f"  Abstract: {p['abstract'][:250]}...")
        print()

        # Relevance
        while True:
            try:
                raw = input("  Relevance (0-3) [q=quit]: ").strip()
            except (KeyboardInterrupt, EOFError):
                pool_path.write_text(text)
                print("\nSaved. Exiting.")
                return 0
            if raw.lower() == "q":
                pool_path.write_text(text)
                print("Saved. Exiting.")
                return 0
            if raw in ("0", "1", "2", "3"):
                relevance = int(raw)
                break
            print("  Invalid — enter 0, 1, 2, or 3.")

        # Thread (optional)
        thread = ""
        if relevance >= 1:
            try:
                thread = input("  Thread name (Enter to skip): ").strip()
            except (KeyboardInterrupt, EOFError):
                pass

        text = _write_label(text, p["arxiv_id"], relevance, thread)
        pool_path.write_text(text)
        print(f"  → Saved: relevance={relevance}" + (f", thread={thread}" if thread else ""))

    print(f"\nAll {len(todo)} papers annotated. File saved: {pool_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
